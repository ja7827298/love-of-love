import tkinter as tk
import time

def shake():
    x = root.winfo_x()
    y = root.winfo_y()
    for i in range(20):
        offset = 15 if i % 2 == 0 else -15
        root.geometry(f"+{x + offset}+{y}")
        root.update()
        time.sleep(0.03)
    root.geometry(f"+{x}+{y}")

root = tk.Tk()
root.title("提示")
root.geometry("300x150")
root.resizable(False, False)
root.attributes("-topmost", True)  # 置顶

label = tk.Label(root, text="运yxeuy行", font=("微软雅黑", 12))
label.pack(expand=True)

btn = tk.Button(root, text="确定", command=root.destroy)
btn.pack(pady=10)

root.after(50, shake)  # 窗口出来后50毫秒开始抖

root.mainloop()
